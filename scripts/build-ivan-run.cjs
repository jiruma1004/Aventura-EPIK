/* Prepare the artist-drawn cutout puppet; animation is in ivan-run.js. */
const fs=require('node:fs'),path=require('node:path'),{execFileSync:run}=require('node:child_process');
const root=path.resolve(__dirname,'..'),lib=path.resolve(root,'../astralia-animation-library/actions');
const input=path.join(lib,'source/ivan-run-rig-v3.png');
const ff=a=>run('ffmpeg',['-v','error','-y',...a],{maxBuffer:30*1024*1024});
const {width:w,height:h}=JSON.parse(run('ffprobe',['-v','error','-show_entries','stream=width,height','-of','json',input])).streams[0];
const bytes=ff(['-i',input,'-f','rawvideo','-pix_fmt','rgba','-']);
const parts=[];
// The generated first row extends past halfway; cut at the actual empty gutter.
let cut=Math.round(h*.54);
for(let f=0;f<5;f++){
 let l=w,r=0,t=h,b=0;const x0=Math.floor(f%3*w/3),x1=Math.floor((f%3+1)*w/3),y0=f<3?0:cut,y1=f<3?cut:h;
 for(let y=y0;y<y1;y++)for(let x=x0;x<x1;x++)if(bytes[(y*w+x)*4+3]>160){l=Math.min(l,x);r=Math.max(r,x);t=Math.min(t,y);b=Math.max(b,y);}
 if(r<l)throw Error('Missing puppet part '+f);parts.push([l,t,r-l+1,b-t+1]);
}
ff(['-i',input,'-c:v','libwebp','-lossless','1',path.join(root,'assets/cast/ivan-run-parts.webp')]);
fs.writeFileSync(path.join(root,'src/cinematics/ivan-run-parts.js'),'/* Generated by scripts/build-ivan-run.cjs. */\nwindow.IvanRunParts='+JSON.stringify(parts)+';\n');
fs.copyFileSync(path.join(root,'assets/cast/ivan-run-parts.webp'),path.join(lib,'sprites/ivan-run-parts.webp'));
fs.writeFileSync(path.join(lib,'sprites/ivan-run-parts.json'),JSON.stringify({parts},null,2));
console.log('Prepared articulated Ivan:',parts);
